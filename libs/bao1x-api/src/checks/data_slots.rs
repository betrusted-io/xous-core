// ============================================================================
//  HOW TO UPDATE THIS FILE  (mechanical rules for the slot-map mirror)
// ============================================================================
// See the SLOT MAP MAINTENANCE header in bao1x_api/offsets.rs for the invariant and the
// <slot-map> tag grammar. This block is the procedure for turning a slot change into
// the right edits here. Read the changed constant's tag, then:
//
// PLACEMENT (which array)
//   targets="all"            -> COMMON_DATA_CLAIMS
//   targets="baosec"         -> BAOSEC_DATA_CLAIMS
//   targets="dabao"          -> DABAO_DATA_CLAIMS
//   targets="baosec,dabao"   -> BOTH BAOSEC_DATA_CLAIMS and DABAO_DATA_CLAIMS
//                               (this is the shape of a baosec.rs const that dabao.rs
//                                re-exports via `pub use`; the claim goes in both target
//                                lists, referencing the same constant.)
//   Rule of thumb: a claim references the constant by path, never a literal slot number,
//   so moving the constant moves the claim automatically. Do not hard-code slot numbers.
//
// KIND
//   registered="primary"  -> primary("NAME", &path::to::CONST)
//   registered="alias"    -> alias("NAME", &path::to::CONST); it must fall inside a
//                            primary in the same (common+target) union. If position="last",
//                            it must be the final slot of `backs` -- there is no automatic
//                            check for that yet (see the note at the bottom).
//   registered="no"       -> ADD NOTHING. The slot is intentionally unmapped and should
//                            show as (free). Leave a one-line comment in the array near
//                            where it would sort, pointing at the constant, so the gap is
//                            not "fixed" later by mistake.
//
// COVERAGE (the ACL cross-check)
//   in-data-slots / in-key-slots on the tag must match reality: if the slot is a member of
//   the target's DATA_SLOTS or KEY_SLOTS array (in offsets/<target>.rs), then check_coverage
//   requires it to be registered as a primary here. Adding a key to KEY_SLOTS without a
//   primary here fails the build; that is intended. registered="no" slots must not appear
//   in either ACL array.
//
// ADDING A NEW TARGET (e.g. a third board)
//   1. Add <TARGET>_DATA_CLAIMS with that target's slots.
//   2. Add a DataMap entry to DATA_MAPS so the host tool iterates it.
//   3. Add the four check_data_map asserts (ZERO_COUNT / OUT_OF_RANGE / PRIMARY_OVERLAP / ALIAS_UNBACKED) for
//      the new (COMMON, <TARGET>) pair.
//   4. Add the two check_coverage asserts for that target's DATA_SLOTS and KEY_SLOTS.
//   Because offsets compiles every target module unconditionally, all of these run on every
//   build regardless of the active config -- that is deliberate.
//
// AFTER EDITING
//   Run:  (cd libs/bao1x-checks && cargo run --bin bao1x-checks)
//   Confirm it prints OK and that the only (free) runs are ones you expect (compare against
//   the reserved/available regions in offsets/common.rs and any registered="no" slots).
//
// NOT YET ENFORCED
//   position="last" on an alias is recorded in the tag but not asserted. If you want it
//   hard-checked (worth it for ERASE_PROOF, whose erase-proof semantics depend on being the
//   final chaff slot), extend check_data_map to verify an alias tagged last ends exactly at
//   its backing primary's end.
// ============================================================================

// ===================== DATA SLOT MAP =====================
// Below is testing code generated by Claude Opus 4.8-high to make sure there are no collisions
// in the data slot map. The idea is to have a build-time check that makes sure everything is consistent.
//
// Companion to `owc_slot_map.rs`, for the RRAM data slots. Two things make this different
// from the one-way counter map:
//
//   1. Intentional aliases. `ERASE_PROOF` deliberately occupies the last slot of the `CHAFF_KEYS` range (see
//      the comment on the constant). A plain "no two claims share a slot" rule would reject a correct map, so
//      claims are tagged Primary or Alias: at most one Primary owns a slot, and every Alias slot must fall
//      inside some Primary. An alias floating in unclaimed space is an error; an undeclared collision between
//      two Primaries is an error.
//
//   2. Per-target layout. baosec and dabao carry different key slots (dabao has no CP_COOKIE or SWAP_KEY).
//      Because the offsets crate compiles every target module unconditionally, both maps are visible here
//      regardless of build config, and both are checked at compile time. Adding a target = adding its claim
//      list and two asserts below.
//
// The `#[cfg]`-free visibility is the whole point: a slot bug on baosec is caught even when
// building for dabao, and vice versa.
//
// Verified: the const fns compile on rustc 1.75, edition 2021, `#![no_std]` (SlotIndex
// destructuring in const context, and the two-slice walk avoids `&mut` params, which are not
// const-stable until 1.83). The real baosec and dabao maps pass; ERASE_PROOF-as-primary,
// a floating alias, and a primary/primary collision each fail the build.

pub use crate::*;

/// Whether a claim owns its slots or merely aliases into another claim's slots.
#[derive(Clone, Copy)]
pub enum SlotKind {
    /// Owns its slots. Two primaries may not share a slot.
    Primary,
    /// Deliberately shares slots with a primary. Must fall entirely within primary space.
    Alias,
}

/// A named claim on a run of data slots, derived from the backing `SlotIndex` so the numbers
/// cannot drift from the real constant.
pub struct DataClaim {
    pub name: &'static str,
    pub first: usize,
    pub count: usize,
    pub kind: SlotKind,
}

// Local const accessors. `SlotIndex::get_base`/`len` exist but are not `const fn`; reading the
// fields directly keeps this self-contained. (If you would rather, mark those two methods
// `const` upstream — `len` must become `range.end - range.start`, since `Range::len` is not
// const — and call them here instead.)
const fn slot_first(s: &SlotIndex) -> usize {
    match s {
        SlotIndex::Data(i, _, _) => *i,
        SlotIndex::DataRange(r, _, _) => r.start,
    }
}
const fn slot_count(s: &SlotIndex) -> usize {
    match s {
        SlotIndex::Data(_, _, _) => 1,
        SlotIndex::DataRange(r, _, _) => r.end - r.start,
    }
}

const fn primary(name: &'static str, s: &SlotIndex) -> DataClaim {
    DataClaim { name, first: slot_first(s), count: slot_count(s), kind: SlotKind::Primary }
}
const fn alias(name: &'static str, s: &SlotIndex) -> DataClaim {
    DataClaim { name, first: slot_first(s), count: slot_count(s), kind: SlotKind::Alias }
}

