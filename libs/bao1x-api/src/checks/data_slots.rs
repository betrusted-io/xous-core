/// A named (common, target) pairing, so the host tool can iterate targets by name.
pub struct DataMap {
    pub name: &'static str,
    pub common: &'static [DataClaim],
    pub target: &'static [DataClaim],
}

pub const DATA_MAPS: &[DataMap] = &[
    DataMap { name: "baosec", common: COMMON_DATA_CLAIMS, target: BAOSEC_DATA_CLAIMS },
    DataMap { name: "dabao", common: COMMON_DATA_CLAIMS, target: DABAO_DATA_CLAIMS },
];

pub const DATA_OK: usize = 0;
pub const DATA_ERR_ZERO_COUNT: usize = 1;
pub const DATA_ERR_OUT_OF_RANGE: usize = 2;
pub const DATA_ERR_PRIMARY_OVERLAP: usize = 3;
pub const DATA_ERR_ALIAS_UNBACKED: usize = 4;

/// Paint every Primary onto a bitmap (rejecting Primary/Primary overlap and bad ranges), then
/// require every Alias slot to be backed by a Primary.
pub const fn check_data_map(common: &[DataClaim], target: &[DataClaim]) -> usize {
    let mut owned = [false; MAX_DATA_SLOTS];
    let slices = [common, target];

    // pass 1: primaries
    let mut si = 0;
    while si < slices.len() {
        let claims = slices[si];
        let mut i = 0;
        while i < claims.len() {
            let first = claims[i].first;
            let count = claims[i].count;
            if count == 0 {
                return DATA_ERR_ZERO_COUNT;
            }
            if first >= MAX_DATA_SLOTS || count > MAX_DATA_SLOTS - first {
                return DATA_ERR_OUT_OF_RANGE;
            }
            if let SlotKind::Primary = claims[i].kind {
                let mut s = first;
                while s < first + count {
                    if owned[s] {
                        return DATA_ERR_PRIMARY_OVERLAP;
                    }
                    owned[s] = true;
                    s += 1;
                }
            }
            i += 1;
        }
        si += 1;
    }

    // pass 2: aliases must land inside primary space
    let mut si = 0;
    while si < slices.len() {
        let claims = slices[si];
        let mut i = 0;
        while i < claims.len() {
            if let SlotKind::Alias = claims[i].kind {
                let first = claims[i].first;
                let count = claims[i].count;
                let mut s = first;
                while s < first + count {
                    if !owned[s] {
                        return DATA_ERR_ALIAS_UNBACKED;
                    }
                    s += 1;
                }
            }
            i += 1;
        }
        si += 1;
    }
    DATA_OK
}

/// Cross-check: every slot the runtime iterates for ACL enforcement (`DATA_SLOTS`, `KEY_SLOTS`)
/// must be owned by a Primary in the map. Catches the map and the ACL arrays drifting apart --
/// e.g. a key added to `KEY_SLOTS` but not registered here.
pub const fn check_coverage(common: &[DataClaim], target: &[DataClaim], slots: &[SlotIndex]) -> bool {
    let mut owned = [false; MAX_DATA_SLOTS];
    let slices = [common, target];
    let mut si = 0;
    while si < slices.len() {
        let claims = slices[si];
        let mut i = 0;
        while i < claims.len() {
            if let SlotKind::Primary = claims[i].kind {
                let first = claims[i].first;
                let count = claims[i].count;
                if first < MAX_DATA_SLOTS && count <= MAX_DATA_SLOTS - first {
                    let mut s = first;
                    while s < first + count {
                        owned[s] = true;
                        s += 1;
                    }
                }
            }
            i += 1;
        }
        si += 1;
    }

    let mut i = 0;
    while i < slots.len() {
        let first = slot_first(&slots[i]);
        let count = slot_count(&slots[i]);
        let mut s = first;
        while s < first + count {
            if s >= MAX_DATA_SLOTS || !owned[s] {
                return false;
            }
            s += 1;
        }
        i += 1;
    }
    true
}

